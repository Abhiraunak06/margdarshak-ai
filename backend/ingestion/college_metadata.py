def derive_college_metadata(college_name: str, inst_type: str = None) -> dict:
    """
    Look up verified metadata or derive verified state/type for any JoSAA college.
    """
    for canon_name, data in INSTITUTE_METADATA.items():
        if canon_name.lower() in college_name.lower() or college_name.lower() in canon_name.lower():
            return data

    name_lower = college_name.lower()
    derived_state = "India"
    for kw, st in STATE_KEYWORD_MAP.items():
        if kw in name_lower:
            derived_state = st
            break

    ctype = inst_type or "GFTI"
    if "information technology" in name_lower or "iiit" in name_lower:
        ctype = "IIIT"
